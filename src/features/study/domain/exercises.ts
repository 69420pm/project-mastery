/**
 * Which Problems the AI gets when it looks for some for KCs (#102, #182,
 * #183): the best three of the unseen Exercises and generated Problems that
 * test any of them. Pure code; the tool feeds it the candidates.
 */

/** What ranking reads of an Exercise or a generated Problem. */
export type RankableExercise = {
  id: string;
  /** The KCs it tests, its first one first. */
  kcs: string[];
  /** 1 to 3. */
  difficulty: number;
  source: ProblemSource;
};

/**
 * Where a Problem comes from, in the order ranking prefers: an Exercise of
 * an old exam, another Exercise, a generated variant of an Exercise, a
 * generated new Problem.
 */
export const PROBLEM_SOURCES = [
  "old_exam",
  "exercise",
  "variant",
  "new",
] as const;

export type ProblemSource = (typeof PROBLEM_SOURCES)[number];

/** Whether the Problem was generated, not taken from the Materials. */
export const isGenerated = (source: ProblemSource) =>
  source === "variant" || source === "new";

/** The most Problems `findProblems` returns. */
export const MAX_PROBLEMS = 3;

/** The difficulty target when the Student has no unassisted success yet. */
const FIRST_TARGET = 1;

/**
 * How the AI is told where an Exercise's solution comes from: printed in
 * the Materials, or none, so it solves the Exercise with the Student.
 */
export function solutionLabel(printed: boolean): string {
  return printed
    ? "from the Materials"
    : "none in the Materials: solve it with the Student";
}

/**
 * How the AI is told where a generated Problem's solution comes from: with
 * a program, its numbers do.
 */
export function generatedSolutionLabel(hasProgram: boolean): string {
  return hasProgram
    ? "generated by the AI, with its numbers computed by code from a program"
    : "generated by the AI without a program: check it before relying on it";
}

/** One above the difficulty of the last unassisted success, capped at 3. */
export function targetDifficulty(lastSuccess: number | null): number {
  return lastSuccess === null ? FIRST_TARGET : Math.min(lastSuccess + 1, 3);
}

/**
 * Up to `MAX_PROBLEMS` of the `candidates` that test any of `kcIds`. In
 * order, each breaking the ties of the one before: more of the given KCs
 * tested, source in `PROBLEM_SOURCES` order, a first KC other than the
 * last Problem's, difficulty nearer `target`, then the candidates' order.
 */
export function rankProblems<Candidate extends RankableExercise>(
  candidates: Candidate[],
  kcIds: string[],
  lastFirstKc: string | null,
  target: number,
): Candidate[] {
  const wanted = new Set(kcIds);
  const varies = (exercise: Candidate) =>
    Number(exercise.kcs[0] !== lastFirstKc);
  return candidates
    .map((exercise) => ({
      exercise,
      matches: new Set(exercise.kcs.filter((id) => wanted.has(id))).size,
    }))
    .filter(({ matches }) => matches > 0)
    .toSorted(
      (a, b) =>
        b.matches - a.matches ||
        PROBLEM_SOURCES.indexOf(a.exercise.source) -
          PROBLEM_SOURCES.indexOf(b.exercise.source) ||
        (lastFirstKc === null ? 0 : varies(b.exercise) - varies(a.exercise)) ||
        Math.abs(a.exercise.difficulty - target) -
          Math.abs(b.exercise.difficulty - target),
    )
    .slice(0, MAX_PROBLEMS)
    .map(({ exercise }) => exercise);
}
