import { describe, expect, test } from "vitest";
import {
  rankExercises,
  solutionLabel,
  type RankableExercise,
} from "./exercises";

const ex = (
  id: string,
  kcs: string[],
  difficulty = 2,
  oldExam = false,
): RankableExercise => ({ id, kcs, difficulty, oldExam });

const ids = (list: RankableExercise[]) => list.map((e) => e.id);

test("solutionLabel tells the AI to check a disputed solution", () => {
  expect(solutionLabel("disputed")).toContain("check it before relying");
  expect(solutionLabel("generated")).toContain("generated by the AI");
});

describe("rankExercises", () => {
  test("keeps only Exercises that test a given KC", () => {
    expect(ids(rankExercises([ex("a", ["x"]), ex("b", ["y"])], ["x"]))).toEqual(
      ["a"],
    );
  });

  test("puts old-exam Exercises first, then more given KCs, then easier ones", () => {
    const list = [
      ex("hard", ["x"], 3),
      ex("easy", ["x"], 1),
      ex("both", ["x", "y"], 3),
      ex("exam", ["x"], 3, true),
    ];
    expect(ids(rankExercises(list, ["x", "y"]))).toEqual([
      "exam",
      "both",
      "easy",
    ]);
  });

  test("gives at most 3 and keeps map order on ties", () => {
    const list = ["a", "b", "c", "d"].map((id) => ex(id, ["x"]));
    expect(ids(rankExercises(list, ["x"]))).toEqual(["a", "b", "c"]);
  });
});
