import { z } from "zod";

// The course model of a Knowledge map (#51, #69). These schemas are the
// source of truth: the tables of the knowledge map migration mirror them,
// `apply_knowledge_map_update` takes a `knowledgeMapSchema` value, and the gold
// map (`evals/gold/*/gold.json`) parses with `courseMapSchema`.

export const KC_TYPES = [
  "fact",
  "concept",
  "procedure",
  "decision",
  "prior",
] as const;

export const BLOOM_LEVELS = [
  "remember",
  "understand",
  "apply",
  "analyze",
  "evaluate",
  "create",
] as const;

export const SEMANTIC_LINK_TYPES = [
  "is_a",
  "part_of",
  "contrasts_with",
  "causes",
  "special_case_of",
  "applies_in",
  "other",
] as const;

/**
 * Where an Exercise's solution stands: printed but unchecked, generated by
 * the build since none was printed, or checked and found right or wrong.
 */
export const SOLUTION_STATUSES = [
  "given",
  "generated",
  "verified",
  "disputed",
] as const;

/**
 * What a Finding reports: a printed solution that does not match, or a
 * remark in the material that excludes or limits exam content.
 */
export const FINDING_KINDS = ["solution_mismatch", "scope"] as const;

/** Whether the Student has answered a Finding in the Brief. */
export const FINDING_STATUSES = ["open", "answered"] as const;

/** The most big ideas a map has (#51's granularity rule). */
export const MAX_BIG_IDEAS = 15;

/**
 * Ids are local to one map, or a stored row's id for a row an update keeps.
 */
const id = z.string().trim().min(1).max(100);
const name = z.string().trim().min(1).max(200);
const description = z.string().trim().min(1).max(1000);

const bigIdeaSchema = z.object({ id, name, description });

/**
 * A knowledge component that `source` chunks teach, or prior knowledge the
 * material assumes, which has no Bloom level, big idea or source. A taught
 * KC comes from the content, or from an exercise that needs it when the
 * content does not teach it.
 */
function kcSchema<Source extends z.ZodType>(source: Source) {
  const common = { id, name, description, sources: z.array(source) };
  return z.discriminatedUnion("type", [
    z.object({
      ...common,
      type: z.enum(KC_TYPES).exclude(["prior"]),
      bloom: z.enum(BLOOM_LEVELS),
      bigIdea: id,
      origin: z.enum(["content", "exercise"]),
    }),
    z.object({
      ...common,
      type: z.literal("prior"),
      bloom: z.null(),
      bigIdea: z.null(),
      origin: z.literal("prior"),
      sources: z.array(source).max(0),
    }),
  ]);
}

/** `from` must be learned before `to`. */
const prerequisiteSchema = z.object({
  from: id,
  to: id,
  extractionConfidence: z.number().min(0).max(1),
});

const semanticLinkSchema = z.object({
  from: id,
  to: id,
  coreType: z.enum(SEMANTIC_LINK_TYPES),
  /** Free text, such as "occurs in". */
  label: name,
});

/**
 * One numeric final result of an Exercise, the key a Student's final value
 * is checked against: such as `{ label: "Thrust", value: 17.5, unit: "kN" }`.
 * The unit is written for mathjs; null for a number without one.
 */
export const finalAnswerSchema = z.object({
  label: z.string().trim().min(1).max(200),
  value: z.number(),
  unit: z.string().trim().min(1).max(50).nullable(),
});

export type FinalAnswer = z.infer<typeof finalAnswerSchema>;

/**
 * An Exercise: one subtask whose question is the `questionChunk`, with the
 * KCs it tests, a short reusable task type such as "compute thrust", its
 * solution's status, a difficulty from 1 (easy) to 3 (hard) and its numeric
 * final answers (null without any, and in maps from before they existed).
 * Only a `generated` solution is stored; a printed one stays in its chunk.
 */
function exerciseSchema<Source extends z.ZodType>(source: Source) {
  return z
    .object({
      id,
      /** As printed, such as "Ex. 7.2b". */
      name,
      questionChunk: source,
      taskType: name,
      solutionStatus: z.enum(SOLUTION_STATUSES),
      solution: z.string().trim().min(1).max(20_000).nullable(),
      difficulty: z.int().min(1).max(3),
      kcs: z.array(id),
      finalAnswers: z.array(finalAnswerSchema).min(1).nullish(),
    })
    .refine(
      (exercise) =>
        (exercise.solutionStatus === "generated") ===
        (exercise.solution !== null),
      "only a generated solution is stored, and it always is",
    );
}

/**
 * Something the build found in the material for the Student to confirm, with
 * its chunks. A stored Finding carries its row id; a new one has none. Its
 * review status and answer are the Student's and stay out of the map.
 */
function findingSchema<Source extends z.ZodType>(source: Source) {
  return z.object({
    id: id.optional(),
    kind: z.enum(FINDING_KINDS),
    text: z.string().trim().min(1).max(2000),
    sources: z.array(source),
  });
}

/**
 * A whole map whose KCs, Exercises and Findings cite chunks as `source`
 * values: chunk ids when stored, chunk positions in a gold set. Every
 * reference must resolve and no link may loop on one KC; the map may still
 * hold prerequisite cycles, which the build breaks before storing it.
 */
export function courseMapSchema<Source extends z.ZodType>(source: Source) {
  return z
    .object({
      bigIdeas: z.array(bigIdeaSchema),
      kcs: z.array(kcSchema(source)),
      prerequisites: z.array(prerequisiteSchema),
      semanticLinks: z.array(semanticLinkSchema),
      /** In reading order. */
      exercises: z.array(exerciseSchema(source)),
      findings: z.array(findingSchema(source)),
    })
    .superRefine((map, ctx) => {
      const issue = (message: string) =>
        ctx.addIssue({ code: "custom", message });
      const bigIdeas = uniqueIds(map.bigIdeas, "big idea", issue);
      const kcs = uniqueIds(map.kcs, "KC", issue);
      uniqueIds(map.exercises, "exercise", issue);
      for (const kc of map.kcs) {
        if (kc.bigIdea !== null && !bigIdeas.has(kc.bigIdea)) {
          issue(`KC ${kc.id} names an unknown big idea ${kc.bigIdea}`);
        }
      }
      for (const exercise of map.exercises) {
        for (const kcId of exercise.kcs) {
          if (!kcs.has(kcId)) {
            issue(`exercise ${exercise.id} names an unknown KC ${kcId}`);
          }
        }
      }
      for (const link of [...map.prerequisites, ...map.semanticLinks]) {
        if (!kcs.has(link.from) || !kcs.has(link.to)) {
          issue(`link ${link.from} → ${link.to} names an unknown KC`);
        } else if (link.from === link.to) {
          issue(`link ${link.from} → ${link.to} loops on one KC`);
        }
      }
    });
}

function uniqueIds(
  items: { id: string }[],
  kind: string,
  issue: (message: string) => void,
) {
  const ids = new Set<string>();
  for (const { id: itemId } of items) {
    if (ids.has(itemId)) issue(`duplicate ${kind} id ${itemId}`);
    ids.add(itemId);
  }
  return ids;
}

/** The map `apply_knowledge_map_update` stores: sources are chunk ids. */
export const knowledgeMapSchema = courseMapSchema(z.uuid());

/** What the build's checks found, stored with the map it checked. */
export const checkReportSchema = z.object({
  /** `content` and `definition` chunks no KC cites. */
  uncoveredChunkIds: z.array(z.uuid()),
  /** Names of non-prior KCs without a source. */
  ungroundedKcs: z.array(name),
  /** Names of KCs without any link. */
  orphanKcs: z.array(name),
  /** The prerequisite edges dropped to break cycles, by KC name. */
  droppedCycleEdges: z.array(
    z.object({ from: name, to: name, extractionConfidence: z.number() }),
  ),
  /** Names of Exercises mapped to no KC, which fails the check. */
  unmappedExercises: z.array(name).default([]),
  /** Names of taught KCs no Exercise tests, reported only. */
  untestedKcs: z.array(name).default([]),
  /** KC pairs still alike enough to be duplicates after merging, reported only. */
  duplicates: z
    .array(z.object({ a: name, b: name, similarity: z.number() }))
    .default([]),
});

/** The input of the Build button's Server Action. */
export const startKnowledgeMapBuildSchema = z.object({ courseId: z.uuid() });

export type KcType = (typeof KC_TYPES)[number];
export type BloomLevel = (typeof BLOOM_LEVELS)[number];
export type SemanticLinkType = (typeof SEMANTIC_LINK_TYPES)[number];
export type SolutionStatus = (typeof SOLUTION_STATUSES)[number];
export type FindingKind = (typeof FINDING_KINDS)[number];
export type FindingStatus = (typeof FINDING_STATUSES)[number];
export type KnowledgeMap = z.infer<typeof knowledgeMapSchema>;
export type CheckReport = z.infer<typeof checkReportSchema>;
